'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const code=fs.readFileSync('js/boot-recovery.js','utf8');
assert.ok(code.includes("searchParams.get('observerLimit')"),'limit diagnostic must be query-gated');
assert.ok(code.includes("searchParams.get('observerSkip')"),'single-source skip diagnostic must be query-gated');
assert.ok(code.includes("searchParams.get('observerReport')==='1'"),'report must be separately query-gated');
assert.ok(code.includes("this.external=/\\/js\\/[^/?#]+\\.js"),'only external JS observers are thresholded');
assert.ok(code.includes('Boolean(options?.subtree)'),'only subtree observers are thresholded');
assert.ok(code.includes('skipSource&&this.sourceName===skipSource'),'requested source observer must be individually skippable');
assert.ok(code.includes('state.skippedIndexes.push(state.tracked)'),'skip diagnostic must record the skipped observer position');
assert.ok(code.includes('limit!==null&&state.tracked>limit'),'limit must remain optional when a source-only skip is active');
assert.ok(code.includes('return this.native.observe(target,options)'),'all non-skipped observers must keep native semantics');
assert.ok(code.includes("if((limit===null&&!skipSource)||typeof env.MutationObserver!=='function')return null"),'normal URLs must leave MutationObserver unchanged');
assert.ok(code.includes("marker+=' ← FIRST BLOCKED'"),'report must identify the first blocked observer');
assert.ok(code.includes("marker+=' ← SKIPPED'"),'report must identify an individually skipped observer');
assert.ok(code.includes('observerThreshold.sources[index-1]'),'report must show source order captured by the guard');
console.log('observer threshold guard contract passed');
