const assert = require('node:assert/strict');
const fs = require('node:fs');
const { loadGame } = require('./harness');
const app = fs.readFileSync('js/app.js', 'utf8');
for (const a of ['hire-workforce-candidate','start-workforce-training','start-workforce-project','workforce-project-status','workforce-project-priority']) assert(app.includes(a), `${a} missing`);
assert(!app.includes('w.recompute(g);const k='), 'render must not recompute');
const { modules } = loadGame({ random: () => 0.5 });
const e = new modules.engine.TycoonEngine();
e.g.configured = true; e.g.hasHeadOffice = true; e.g.officeCapacity = 100; e.g.companyCash = 100000000;
e.g.finance = modules.finance.defaultFinanceState(e.g);
e.g.departments.hr = { ...modules.data.MASTER.departments.find(d => d.id === 'hr'), established: true }; e.g.departmentStaff.hr = 3;
e.g.departments.dx = { ...modules.data.MASTER.departments.find(d => d.id === 'dx'), established: true }; e.g.departmentStaff.dx = 5;
modules.workforce.migrateV7(e.g);
let saves = 0, emits = 0; e.save = () => { saves++; }; e.emit = () => { emits++; }; e.notify = (message) => { e.g.news.unshift(message); };
e.g.workforceCandidates.push({ candidateID: 'ui-cand', roleID: 'hr', departmentID: 'hr', headcount: 1, averageSkill: 70, averageExperience: 30, weeklySalaryPerPerson: 80000, recruitmentFee: 100, onboardingWeeks: 1, expectedMorale: 60, remoteCompatibility: .8, expiresWeek: e.g.week + 4, status: 'open' });
assert.equal(e.hireWorkforceCandidate('ui-cand'), true); assert.equal(saves, 1); assert.equal(emits, 1);
const team = e.g.workforceTeams.find(t => t.departmentID === 'hr');
assert.equal(e.startWorkforceTraining(team.teamID, 'basic'), true); assert.equal(saves, 2); assert.equal(emits, 2);
assert.equal(e.startWorkforceProject('dx-rollout'), true); assert.equal(saves, 3); assert.equal(emits, 3);
const p = e.g.workforceProjects[0]; p.status = 'active';
assert.equal(e.setWorkforceProjectStatus(p.projectID, 'paused'), true); assert.equal(saves, 4); assert.equal(emits, 4);
assert.equal(e.setWorkforceProjectStatus(p.projectID, 'active'), true); assert.equal(saves, 5); assert.equal(emits, 5);
assert.equal(e.changeWorkforceProjectPriority(p.projectID, 1), true); assert.equal(saves, 6); assert.equal(emits, 6);
assert.equal(e.setWorkforceProjectStatus(p.projectID, 'cancelled'), true); assert.equal(saves, 7); assert.equal(emits, 7);
assert.equal(e.hireWorkforceCandidate('missing'), false);
assert.equal(e.startWorkforceTraining('missing', 'basic'), false);
assert.equal(e.startWorkforceProject('missing'), false);
console.log('workforce ui actions ok');
