const { ctx, modules } = loadGame({ random: () => 0.42 });
const engine = ctx.__ct_engine;
engine.g.configured = true;
ctx.__ct_ui.showSetup = false;
engine.g.selectedTab = 'ma';
engine.g.companyCash = 1_000_000_000;
engine.g.departments.investment = { established: true };
engine.g.acquisitionTargets = [{ id: 'ui-pure', name: 'UI純粋物流', domain: '物流', valuation: 100_000_000, sales: 80_000_000, operatingProfit: 8_000_000, growth: .1, risk: .2, synergy: .12, friendly: true, expiresWeek: engine.g.week + 20 }, { id: 'ui-lost', name: 'UI敗北物流', domain: '物流', valuation: 100_000_000, sales: 80_000_000, operatingProfit: 8_000_000, growth: .1, risk: .2, synergy: .12, friendly: true, expiresWeek: engine.g.week + 20, dealStatus: 'lost' }, { id: 'ui-expired', name: 'UI期限切物流', domain: '物流', valuation: 100_000_000, sales: 80_000_000, operatingProfit: 8_000_000, growth: .1, risk: .2, synergy: .12, friendly: true, expiresWeek: engine.g.week + 20, dealStatus: 'expired' }];
engine.normalize();
modules.maDealRoom.ensure(engine.g);
assert(engine.openMADealRoom('ui-pure'));
const openDeal=engine.g.maDealRooms[0];
const before = JSON.parse(JSON.stringify(engine.g));
let saved = 0, changed = 0, notified = 0;
engine.addEventListener('saved', () => { saved += 1; });
engine.addEventListener('change', () => { changed += 1; });
engine.addEventListener('notify', () => { notified += 1; });
const writesBefore = ctx.__localStorageHistory.setItem.length;
engine.emit('change');
engine.emit('change');
assert.deepStrictEqual(JSON.parse(JSON.stringify(engine.g)), before, 'rendering M&A tab must not mutate state');
assert.equal(ctx.__localStorageHistory.setItem.length - writesBefore, 0, 'rendering must not write localStorage');
assert.equal(saved, 0, 'rendering must not emit saved');
assert.equal(notified, 0, 'rendering must not notify');
const html = ctx.document.getElementById('app').innerHTML;
assert(html.includes('data-ma-dd-quote'), 'DD quote selector rendered');
assert(html.includes('data-ma-dd-duration'), 'DD duration selector rendered');
assert(html.includes('1週'), 'screening displays one week');
assert(html.includes('2週'), 'financial displays two weeks');
assert(html.includes('4週'), 'full displays four weeks');
assert(html.includes('今回費用'), 'initial DD fee label rendered');
assert(/信頼度72(?:\.0)?%/.test(html), 'financial confidence rendered');
assert(html.includes('初期検討'), 'deal room status is Japanese');
assert(html.includes('案件期限まで'), 'active deal displays normal deadline label');
openDeal.status = 'accepted'; openDeal.acceptedTerms = { closingDeadlineWeek: engine.g.week + 4 };
engine.emit('change');
const acceptedHtml = ctx.document.getElementById('app').innerHTML;
assert(acceptedHtml.includes('契約受諾'), 'accepted status is Japanese');
