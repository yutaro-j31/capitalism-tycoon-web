openDeal.status = 'expired';
engine.emit('change');
assert(ctx.document.getElementById('app').innerHTML.includes('案件終了'), 'terminal deal shows ended label');
for (const [status,label] of Object.entries(modules.maDealRoom.STATUS_LABELS)) assert(appSource.includes(label) || modules.maDealRoom.STATUS_LABELS[status] === label, `${status} label exists`);
assert.equal(changed, 4, 'only explicit render-triggering change events should be observed');
