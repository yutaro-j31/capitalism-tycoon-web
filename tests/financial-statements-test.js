const { loadGame } = require('./harness');
const { engineModule, modules } = loadGame({ random: (()=>{let x=1; return ()=>((x=(x*16807)%2147483647)/2147483647);})() });
const { TycoonEngine } = engineModule;
const finance = modules.finance;
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const e=new TycoonEngine(); e.g.configured=true;
e.borrow(1000000,'company');
const before=e.g.companyCash;
finance.addFixedAsset(e.g,{assetID:'asset-1',acquisitionCost:520000,usefulLifeWeeks:52,salvageValue:0});
finance.event(e.g,'capitalExpenditure',520000,{cashEffect:-520000,assetEffect:520000,sourceType:'test',sourceID:'capex'});
e.g.companyCash-=520000;
finance.recordWeekly(e.g,{beginningCash:before,stores:[{storeID:'s1',businessID:'ramen',name:'店',sales:100000,variable:30000,rent:10000,wage:20000,repair:5000}],other:{interest:-1000,tax:-2000}});
const st=finance.buildStatements(e.g,before,'52');
assert(st.profitAndLoss.ebitda===35000,'EBITDA calculation');
assert(st.profitAndLoss.depreciation>0,'depreciation recorded');
assert(st.profitAndLoss.operatingIncome===st.profitAndLoss.ebitda-st.profitAndLoss.depreciation,'operating income');
assert(st.balanceSheet.assets.cashAndDeposits===e.g.companyCash,'cash equals BS cash');
assert(Math.abs(st.balanceSheet.assets.totalAssets-st.balanceSheet.liabilities.totalLiabilities-st.balanceSheet.equity.totalEquity)<0.1,'balance sheet balances');
assert(st.cashFlow.endingCash===e.g.companyCash,'CF ending cash');
console.log('financial statement checks passed');
