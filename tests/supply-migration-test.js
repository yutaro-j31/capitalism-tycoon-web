const assert=require('node:assert/strict');
const {loadGame}=require('./harness');
const {modules}=loadGame();
const {createInitialState,migrateSave}=modules.engine;
const s=createInitialState({configured:true});
s.saveVersion=5;s.companyCash=12_345_678;s.personalCash=7_654_321;s.companyDebt=1_200_000;
s.market[0].priceHistory=[{week:1,price:s.market[0].price},{week:2,price:s.market[0].price+1}];
s.properties.push({id:'prop-x',name:'土地X',kind:'土地',owner:'company',price:1000000,value:1000000,purchasePrice:1000000});
s.subsidiaries.push({id:'sub-x',name:'子会社X',status:'active',carryingBookValue:500000,weeklyProfit:0});
s.stores.push({id:'legacy-r1',businessID:'ramen',prefID:'tokyo',name:'old1',status:'open'});
s.stores.push({id:'legacy-r2',businessID:'ramen',prefID:'osaka',name:'old2',status:'open'});
s.stores.push({id:'legacy-cafe',businessID:'cafe',prefID:'tokyo',name:'cafe',status:'open'});
s.finance=modules.finance.defaultFinanceState(s);s.finance.balances.accountsPayable=12345;s.finance.openingLiabilities+=12345;s.finance.openingEquity-=12345;s.finance.openingRetainedEarnings-=12345;
const cash=s.companyCash,personal=s.personalCash,history=JSON.stringify(s.market[0].priceHistory);
const m=migrateSave(s);assert(m.ok,m.errors.join('\n'));const g=m.state;
assert.equal(g.saveVersion,6);assert.equal(g.companyCash,cash);assert.equal(g.personalCash,personal);assert.equal(JSON.stringify(g.market[0].priceHistory),history);
assert(g.inventoryByStoreID['legacy-r1']);assert(g.inventoryByStoreID['legacy-r2']);assert(!g.inventoryByStoreID['legacy-cafe']);
const physical=modules.supply.physicalInventoryValue(g);assert(physical>0);assert.equal(Math.round(g.finance.balances.inventory),Math.round(physical));
assert.equal(g.finance.balances.accountsPayable,12345);assert.equal(g.supplyAccountsPayableBalance,0);
assert.equal(modules.finance.validate(g).ok,true,modules.finance.validate(g).errors.join('\n'));
assert.equal(modules.supply.validate(g).ok,true,modules.supply.validate(g).errors.join('\n'));
const lots=g.inventoryByStoreID['legacy-r1'].materials.ramen_noodles.lots.length, inv=physical;
const m2=migrateSave(g);assert(m2.ok,m2.errors.join('\n'));assert.equal(m2.state.inventoryByStoreID['legacy-r1'].materials.ramen_noodles.lots.length,lots);assert.equal(modules.supply.physicalInventoryValue(m2.state),inv);
console.log('supply migration ok');
