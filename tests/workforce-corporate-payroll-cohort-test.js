const assert=require('node:assert/strict');
const {loadGame}=require('./harness');
const {modules}=loadGame({random:()=>.5});
const e=new modules.engine.TycoonEngine();
e.g.configured=true;e.g.hasHeadOffice=true;e.g.officeCapacity=100;e.g.companyCash=100000000;e.g.finance=modules.finance.defaultFinanceState(e.g);
e.g.departments.hr={...modules.data.MASTER.departments.find(d=>d.id==='hr'),established:true};
e.g.departmentStaff.hr=3;
modules.workforce.migrateV7(e.g);
let team=e.g.workforceTeams.find(t=>t.departmentID==='hr'&&!t.storeID);
team.averageWeeklySalary=65000;
team.corporatePayrollCohorts=[{cohortID:'hr-base-pay',candidateID:null,roleID:'hr',headcount:3,weeklySalaryPerPerson:65000,hiredWeek:e.g.week,status:'active',base:true}];
modules.workforce.recompute(e.g);
assert.equal(modules.workforce.validate(e.g).ok,true,modules.workforce.validate(e.g).errors.join('\n'));
e.g.workforceCandidates.push({candidateID:'corp-pay-hi',roleID:'hr',departmentID:'hr',headcount:2,averageSkill:80,averageExperience:50,weeklySalaryPerPerson:100000,recruitmentFee:100,onboardingWeeks:1,expectedMorale:70,remoteCompatibility:.8,expiresWeek:10,status:'open'});
e.hireWorkforceCandidate('corp-pay-hi');
assert.equal(modules.workforce.validate(e.g).ok,true,modules.workforce.validate(e.g).errors.join('\n'));
team=e.g.workforceTeams.find(t=>t.departmentID==='hr'&&!t.storeID);
assert.equal(team.onboardingHeadcount,2);
assert.equal(modules.workforce.weeklyPayroll(e.g),395000);
const before=e.g.companyCash;
e.advanceWeek(false);
assert.equal(modules.workforce.validate(e.g).ok,true,modules.workforce.validate(e.g).errors.join('\n'));
assert.equal(modules.workforce.weeklyPayroll(e.g),395000);
const tx=e.g.finance.transactions.find(t=>t.sourceType==='weekly-deptCost'&&t.week===2);
assert(tx);
assert.equal(tx.amount,395000);
assert.equal(modules.finance.validate(e.g).ok,true,modules.finance.validate(e.g).errors.join('\n'));
const weekCash=e.g.finance.transactions.filter(t=>t.week===2).reduce((a,t)=>a+t.cashEffect,0);
assert.equal(e.g.companyCash,before+weekCash);
const saved=JSON.parse(JSON.stringify(e.g));
assert.equal(modules.workforce.weeklyPayroll(saved),395000);
assert.equal(modules.workforce.validate(saved).ok,true,modules.workforce.validate(saved).errors.join('\n'));
console.log('workforce corporate payroll cohort ok');
