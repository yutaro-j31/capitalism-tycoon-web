const assert = require('node:assert/strict');
const fs = require('node:fs');
const { loadGame } = require('./harness');
const { ctx, modules } = loadGame({ random: () => 0.123 });
const { engine, foundingTutorial, ceoDashboard } = modules;
assert.ok(foundingTutorial, 'foundingTutorial module is registered');
assert.equal(engine.SAVE_KEY, 'capitalism_tycoon_web_v1');
assert.equal(engine.SAVE_VERSION, 9);
assert.equal(foundingTutorial.STEPS.length, 10, 'fixed 10 step roadmap');
assert.deepEqual(Array.from(foundingTutorial.STEPS, s => s.id), ['dashboard','first_store','unit_economics','first_week','weekly_recap','first_improvement','cash_runway','growth_step','organization','graduation']);
const currentID = state => foundingTutorial.build(state).current?.id || null;
const isDone = (model, id) => model.steps.find(s => s.id === id).completed;
const fresh = engine.createInitialState({ configured: true });
const before = JSON.stringify(fresh);
const a = foundingTutorial.build(fresh);
const b = foundingTutorial.build(fresh);
assert.deepEqual(a, b, 'same state returns deterministic model');
assert.equal(JSON.stringify(fresh), before, 'model generation does not mutate save JSON');
assert.equal(a.displayMode, 'guide');
assert.equal(a.current.id, 'dashboard');
assert.equal(a.completedCount, 0);
fresh.selectedTab = 'home';
fresh.stores.push({ id:'s1', businessID:'ramen', prefID:'tokyo', name:'本店', status:'open', quality:0, brand:0, condition:100 });
assert.equal(currentID(fresh), 'unit_economics');
fresh.supplySettingsByStoreID = { s1: { autoPolicy:'balanced' } };
assert.equal(currentID(fresh), 'first_week');
fresh.week = 2; fresh.reports = [{ week:1, sales:1000000, profit:100000, expenses:700000 }]; fresh.lastReport = fresh.reports[0];
let m = foundingTutorial.build(fresh);
assert.equal(currentID(fresh), 'weekly_recap', 'first report exposes weekly recap step');
assert.equal(isDone(m, 'weekly_recap'), false, 'one report is not enough to complete weekly recap');
fresh.reports.push({ week:2, sales:1200000, profit:150000, expenses:750000 }); fresh.lastReport = fresh.reports[1];
m = foundingTutorial.build(fresh);
assert.equal(currentID(fresh), 'first_improvement', 'two reports move to improvement, not cash runway');
assert.equal(isDone(m, 'weekly_recap'), true, 'two reports complete weekly recap');
assert.equal(isDone(m, 'first_improvement'), false, 'reports alone do not complete improvement');
fresh.businesses.find(b => b.id === 'ramen').brand += 2;
m = foundingTutorial.build(fresh);
assert.equal(currentID(fresh), 'cash_runway', 'actual business improvement exposes cash runway');
assert.equal(isDone(m, 'first_improvement'), true);
assert.equal(isDone(m, 'cash_runway'), false, 'cash runway is not completed by initial cash or two reports');
fresh.week = 3; fresh.companyCash = 6000000; fresh.reports.push({ week:3, sales:1300000, profit:200000, expenses:700000 }); fresh.lastReport = fresh.reports[2];
assert.equal(currentID(fresh), 'growth_step');
fresh.stores.push({ id:'s2', businessID:'ramen', prefID:'tokyo', name:'2号店', status:'open' });
assert.equal(currentID(fresh), 'organization');
fresh.hasHeadOffice = true; fresh.departments = { operations: { name:'運営部' } };
m = foundingTutorial.build(fresh);
assert.equal(currentID(fresh), 'graduation');
assert.equal(m.complete, false);
fresh.companyCash = 7000000;
m = foundingTutorial.build(fresh);
assert.equal(m.displayMode, 'complete');
assert.equal(m.complete, true);
const training = engine.createInitialState({ configured: true });
training.stores.push({ id:'s1', businessID:'ramen', prefID:'tokyo', name:'本店', status:'open' });
training.supplySettingsByStoreID = { s1: { autoPolicy:'balanced' } };
training.week = 2; training.reports = [{week:1},{week:2}]; training.workforceTrainings = [{ status:'active' }];
assert.equal(foundingTutorial._internals.hasImprovement(training), true, 'training is a safe improvement path');
for (const difficulty of ['easy','normal','hard']) {
  const state = engine.createInitialState({ configured: true, difficulty });
  assert.equal(isDone(foundingTutorial.build(state), 'cash_runway'), false, `${difficulty} initial cash does not complete cash runway`);
}
const listed = engine.createInitialState({ configured: true });
listed.publicCompany = true; listed.week = 180; listed.reports = [{week:179},{week:180}];
m = foundingTutorial.build(listed);
assert.equal(m.displayMode, 'summary');
assert.equal(m.current, null, 'summary mode has no forced current step');
assert.equal(m.complete, false);
assert.equal(m.steps.find(s => s.id === 'first_store').current, false, 'listed save must not show initial store prompt as current');
const impactOne = ceoDashboard.weeklyImpact(fresh, { companyValue: 10000000 });
assert.ok(Array.isArray(impactOne.metrics) && impactOne.metrics.length === 4, 'weekly impact model is available for dashboard card');
const localWritesBefore = ctx.__localStorageHistory.setItem.length;
const pureBefore = JSON.stringify(listed);
foundingTutorial.build(listed);
assert.equal(JSON.stringify(listed), pureBefore, 'summary build does not mutate save JSON');
assert.equal(ctx.__localStorageHistory.setItem.length, localWritesBefore, 'build does not write localStorage');
assert.doesNotMatch(fs.readFileSync('js/founding-tutorial.js','utf8'), /Math\.random|localStorage|advanceWeek|\.save\(/, 'tutorial model is read-only and deterministic');
console.log('founding tutorial model tests passed');
