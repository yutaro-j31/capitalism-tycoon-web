const assert = require('node:assert/strict');
const fs = require('node:fs');
const { loadGame } = require('./harness');
const { ctx, modules } = loadGame({ random: () => 0.123 });
const { engine, foundingTutorial } = modules;
assert.ok(foundingTutorial, 'foundingTutorial module is registered');
assert.equal(engine.SAVE_KEY, 'capitalism_tycoon_web_v1');
assert.equal(engine.SAVE_VERSION, 9);
assert.equal(foundingTutorial.STEPS.length, 10, 'fixed 10 step roadmap');
assert.deepEqual(Array.from(foundingTutorial.STEPS, s => s.id), ['dashboard','first_store','unit_economics','first_week','weekly_recap','first_improvement','cash_runway','growth_step','organization','graduation']);
const fresh = engine.createInitialState({ configured: true });
const before = JSON.stringify(fresh);
const a = foundingTutorial.build(fresh);
const b = foundingTutorial.build(fresh);
assert.deepEqual(a, b, 'same state returns deterministic model');
assert.equal(JSON.stringify(fresh), before, 'model generation does not mutate save JSON');
assert.equal(a.current.id, 'dashboard');
assert.equal(a.completedCount, 0);
fresh.selectedTab = 'home';
fresh.stores.push({ id:'s1', businessID:'ramen', prefID:'tokyo', name:'本店', status:'open', quality:0, brand:0, condition:100 });
let m = foundingTutorial.build(fresh);
assert.equal(m.steps.find(s => s.id === 'first_store').completed, true);
assert.equal(m.current.id, 'unit_economics');
fresh.supplySettingsByStoreID = { s1: { autoPolicy:'balanced' } };
m = foundingTutorial.build(fresh);
assert.equal(m.current.id, 'first_week');
fresh.week = 2; fresh.reports = [{ week:1, sales:1000000, profit:100000, expenses:700000 }]; fresh.lastReport = fresh.reports[0];
m = foundingTutorial.build(fresh);
assert.equal(m.current.id, 'first_improvement');
fresh.reports.push({ week:2, sales:1200000, profit:150000, expenses:750000 });
fresh.companyCash = 6000000;
m = foundingTutorial.build(fresh);
assert.equal(m.steps.find(s => s.id === 'first_improvement').completed, true);
assert.equal(m.steps.find(s => s.id === 'cash_runway').completed, true);
fresh.stores.push({ id:'s2', businessID:'ramen', prefID:'tokyo', name:'2号店', status:'open' });
fresh.hasHeadOffice = true; fresh.departments = { operations: { name:'運営部' } };
m = foundingTutorial.build(fresh);
assert.equal(m.complete, true);
const listed = engine.createInitialState({ configured: true });
listed.publicCompany = true; listed.week = 180; listed.reports = [{week:179},{week:180}];
m = foundingTutorial.build(listed);
assert.notEqual(m.current.id, 'first_store', 'listed save must not show initial store prompt as current');
assert.ok(['guide','summary'].includes(m.displayMode));
const localWritesBefore = ctx.__localStorageHistory.setItem.length;
foundingTutorial.build(listed);
assert.equal(ctx.__localStorageHistory.setItem.length, localWritesBefore, 'build does not write localStorage');
assert.doesNotMatch(fs.readFileSync('js/founding-tutorial.js','utf8'), /Math\.random|localStorage|advanceWeek|\.save\(/, 'tutorial model is read-only and deterministic');
console.log('founding tutorial model tests passed');
