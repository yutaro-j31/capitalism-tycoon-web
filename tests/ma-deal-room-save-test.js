const assert = require('assert');
const { load } = require('./ma-deal-room-test-helpers');
const { engineModule, dr } = load();
const { TycoonEngine, SAVE_KEY, SAVE_VERSION } = engineModule;

(async () => {
  const e = new TycoonEngine();
  e.g.configured = true;
  e.g.companyCash = 1_000_000_000;
  e.g.departments.investment = { established: true };
  e.g.acquisitionTargets = [{ id: 'legacy', name: 'Legacy物流', domain: '物流', valuation: '100000000', sales: null, operatingProfit: 8000000, growth: .1, risk: .2, synergy: .1, friendly: true, expiresWeek: 999 }];
  e.normalize();
  assert.equal(e.g.saveVersion, 9);
  assert.equal(SAVE_KEY, 'capitalism_tycoon_web_v1');
  assert.equal(SAVE_VERSION, 9);
  assert.equal(e.g.acquisitionTargets[0].dealStatus, 'available');
  assert.equal(e.openMADealRoom('legacy'), true);
  const d = e.g.maDealRooms[0];
  assert.equal(e.startMADueDiligence(d.id, 'screening'), true);
  e.g.week += 1; dr.processDealWeek(e.g, e.g.week);
  assert.equal(d.status, 'ready');
  assert.equal(e.submitMAOffer(d.id, { method: 'friendly', offerPrice: Math.min(250000000, Math.max(d.sellerAsk * 1.1, d.valuationBridge.recommendedMaximumPrice)) }), true);
  e.g.week += 1; dr.processDealWeek(e.g, e.g.week);
  const preservedBeforeSave = JSON.parse(JSON.stringify({ deal: e.g.maDealRooms[0], truth: e.g.maTargetTruthByID }));
  assert.equal(e.save(), true);
  const raw = localStorage.getItem(SAVE_KEY);
  assert.ok(raw, 'main save must be written');
  const loaded = TycoonEngine.load();
  assert.deepStrictEqual(JSON.parse(JSON.stringify({ deal: loaded.g.maDealRooms[0], truth: loaded.g.maTargetTruthByID })), preservedBeforeSave, 'main save reload must preserve deal room state');
  assert.equal(typeof loaded.save, 'function');
  assert.equal(typeof loaded.loadSlot, 'function');
  assert.equal(loaded.save(1), true, 'slot save must succeed');
  assert.ok(localStorage.getItem(`${SAVE_KEY}_slot_1`), 'slot payload must exist');
  const slotLoaded = new TycoonEngine();
  assert.equal(slotLoaded.loadSlot(1), true, 'slot load must succeed');
  assert.deepStrictEqual(JSON.parse(JSON.stringify({ deal: slotLoaded.g.maDealRooms[0], truth: slotLoaded.g.maTargetTruthByID })), preservedBeforeSave, 'slot load must restore deal room state');
  const exported = loaded.exportSave();
  assert.ok(exported instanceof Blob, 'exportSave must return a Blob');
  const imported = new TycoonEngine();
  imported.importSave(await exported.text());
  assert.deepStrictEqual(JSON.parse(JSON.stringify({ deal: imported.g.maDealRooms[0], truth: imported.g.maTargetTruthByID })), preservedBeforeSave, 'export/import must restore deal room state');
  const future = JSON.parse(raw);
  future.saveVersion = 999;
  const migrated = engineModule.migrateSave(future);
  assert.equal(migrated.ok, false);
  assert.equal(migrated.version, 999);
  console.log('ma deal room save tests passed');
})();
