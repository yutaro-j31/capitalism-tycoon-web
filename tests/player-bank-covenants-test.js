const assert = require('node:assert');
const { loadGame } = require('./harness');
const { modules } = loadGame();
const { engine, finance, playerBankCovenants, playerCreditRating, playerDebtRefinancing, playerLiquidityRunway, playerFundingConcentration, playerDebtMaturityReserve } = modules;
assert.ok(playerBankCovenants?.__installed, 'bank covenant module must be installed');
assert.ok(playerCreditRating?.__installed, 'credit rating module must be installed');
assert.ok(playerDebtRefinancing?.__installed, 'debt refinancing module must be installed');
assert.ok(playerLiquidityRunway?.__installed, 'liquidity runway module must be installed');
assert.ok(playerFundingConcentration?.__installed, 'funding concentration module must be installed');
assert.ok(playerDebtMaturityReserve?.__installed, 'debt maturity reserve module must be installed');
assert.equal(engine.SAVE_KEY, 'capitalism_tycoon_web_v1');
assert.equal(engine.SAVE_VERSION, 9);
const state = engine.createInitialState({ configured: true });
state.finance = finance.defaultFinanceState(state);
state.week = 20;
state.companyCash = 10_000_000;
state.companyDebt = 60_000_000;
state.companyCredit = 70;
state.lastReport = { interest: 1_000_000, operatingProfit: 500_000 };
const game = new engine.TycoonEngine(state);
const first = playerBankCovenants.evaluate(game);
assert.equal(first.status, 'warning');
assert.equal(first.breachWeeks, 1);
assert.ok(first.rateSurcharge > 0);
assert.equal(game.g.companyCredit, 69);
assert.equal(playerBankCovenants.evaluate(game).history.length, 1, 'same-week evaluation must be idempotent');
const concentrated = playerFundingConcentration.evaluate(game);
assert.equal(concentrated.status, 'concentrated');
assert.equal(concentrated.largestShare, 1);
assert.equal(concentrated.rateSurcharge, .005);
assert.equal(playerFundingConcentration.evaluate(game).history.length, 1, 'same-week concentration evaluation must be idempotent');
const weakRating = playerCreditRating.evaluate(game);
assert.ok(['BB','B','CCC'].includes(weakRating.grade));
assert.ok(weakRating.rateAdjustment > 0);
assert.equal(playerCreditRating.evaluate(game).history.length, 1, 'same-week rating evaluation must be idempotent');
game.g.week++;
const second = playerBankCovenants.evaluate(game);
assert.equal(second.status, 'breach');
assert.equal(second.breachWeeks, 2);
playerCreditRating.evaluate(game);
assert.ok(game.companyWeeklyBorrowRate() > modules.playerDebtService.negotiatedRate(game));
const refinancing = playerDebtRefinancing.normalize(game);
refinancing.nextMaturityWeek = game.g.week + 4;
game.g.companyCash = 7_000_000;
const reserve = playerDebtMaturityReserve.evaluate(game);
assert.equal(reserve.status, 'critical');
assert.equal(reserve.weeksToMaturity, 4);
assert.equal(reserve.targetAmount, 6_000_000);
assert.ok(reserve.coverageRatio < reserve.criticalCoverage);
assert.equal(playerDebtMaturityReserve.evaluate(game).history.length, 1, 'same-week reserve evaluation must be idempotent');
const creditBeforeReservePenalty = game.g.companyCredit;
game.g.week++;
playerDebtMaturityReserve.evaluate(game);
assert.equal(game.g.companyCredit, creditBeforeReservePenalty - 1, 'persistent critical maturity coverage reduces credit every second week');
game.g.companyCash = 20_000_000;
game.g.week++;
const preparedReserve = playerDebtMaturityReserve.evaluate(game);
assert.equal(preparedReserve.status, 'adequate');
assert.ok(preparedReserve.coverageRatio >= 1);
assert.equal(preparedReserve.criticalStreak, 0);
game.g.finance.debtRefinancing.nextMaturityWeek = game.g.week;
game.g.finance.debtRefinancing.lastProcessedWeek = game.g.week - 1;
game.g.finance.debtRefinancing.history = [];
const cashBeforeRefinancing = game.g.companyCash;
const debtBeforeRefinancing = game.g.companyDebt;
const stressed = playerDebtRefinancing.process(game);
assert.equal(stressed.status, 'stressed');
assert.ok(stressed.history.length === 1);
assert.ok(stressed.history[0].fee > 0);
assert.ok(game.g.companyCash < cashBeforeRefinancing);
assert.ok(game.g.companyDebt <= debtBeforeRefinancing);
assert.equal(stressed.nextMaturityWeek, game.g.week + 26);
assert.equal(playerDebtRefinancing.process(game).history.length, 1, 'same-week maturity processing must be idempotent');
game.g.companyCash = 3_000_000;
game.g.lastReport = { interest: 500_000, operatingProfit: -1_000_000 };
const liquidity = playerLiquidityRunway.evaluate(game);
assert.equal(liquidity.status, 'critical');
assert.equal(liquidity.runwayWeeks, 2);
assert.equal(playerLiquidityRunway.evaluate(game).history.length, 1, 'same-week liquidity evaluation must be idempotent');
const creditBeforeLiquidityPenalty = game.g.companyCredit;
game.g.week++;
playerLiquidityRunway.evaluate(game);
assert.equal(game.g.companyCredit, creditBeforeLiquidityPenalty - 1, 'persistent critical liquidity reduces credit every second week');
game.g.companyCash = 100_000_000;
game.g.companyDebt = 40_000_000;
game.g.companyCredit = 95;
game.g.lastReport = { interest: 100_000, operatingProfit: 2_000_000 };
game.g.week++;
const cured = playerBankCovenants.evaluate(game);
assert.equal(cured.status, 'warning');
assert.equal(cured.breachWeeks, 1);
assert.ok(cured.rateSurcharge < second.rateSurcharge);
const strongRating = playerCreditRating.evaluate(game);
assert.ok(['AAA','AA','A'].includes(strongRating.grade));
assert.ok(strongRating.rateAdjustment < 0);
const stableLiquidity = playerLiquidityRunway.evaluate(game);
assert.equal(stableLiquidity.status, 'stable');
assert.equal(stableLiquidity.runwayWeeks, 99);
assert.equal(stableLiquidity.criticalStreak, 0);
const healthyRefinancing = playerDebtRefinancing.normalize(game);
healthyRefinancing.nextMaturityWeek = game.g.week;
healthyRefinancing.lastProcessedWeek = -1;
const healthyDebtBefore = game.g.companyDebt;
const completed = playerDebtRefinancing.process(game);
assert.equal(completed.status, 'refinanced');
assert.ok(game.g.companyDebt < healthyDebtBefore);
assert.equal(completed.nextMaturityWeek, game.g.week + completed.termWeeks);
const concentrationState = engine.createInitialState({ configured: true });
concentrationState.finance = finance.defaultFinanceState(concentrationState);
concentrationState.week = 10;
concentrationState.companyDebt = 100_000_000;
concentrationState.companyCredit = 80;
concentrationState.finance.loans = [{status:'active',outstandingPrincipal:100_000_000}];
const concentrationGame = new engine.TycoonEngine(concentrationState);
const concentrationCredit = concentrationGame.g.companyCredit;
for(let i=0;i<4;i++){playerFundingConcentration.evaluate(concentrationGame);concentrationGame.g.week++;}
assert.equal(concentrationGame.g.companyCredit, concentrationCredit - 1, 'persistent single-lender concentration reduces credit every fourth week');
concentrationGame.g.finance.loans = [
  {status:'active',outstandingPrincipal:40_000_000},
  {status:'active',outstandingPrincipal:30_000_000},
  {status:'active',outstandingPrincipal:30_000_000}
];
const diversified = playerFundingConcentration.evaluate(concentrationGame);
assert.equal(diversified.status, 'diversified');
assert.equal(diversified.rateSurcharge, 0);
assert.equal(diversified.concentratedStreak, 0);
for(let i=0;i<60;i++){game.g.week++;playerBankCovenants.evaluate(game);playerCreditRating.evaluate(game);playerLiquidityRunway.evaluate(game);playerFundingConcentration.evaluate(game);playerDebtMaturityReserve.evaluate(game);}
assert.ok(game.g.finance.bankCovenants.history.length <= 52);
assert.ok(game.g.finance.creditRating.history.length <= 52);
assert.ok(game.g.finance.liquidityRunway.history.length <= 52);
assert.ok(game.g.finance.fundingConcentration.history.length <= 52);
assert.ok(game.g.finance.debtMaturityReserve.history.length <= 52);
for(let i=0;i<30;i++){game.g.finance.debtRefinancing.nextMaturityWeek=game.g.week;game.g.finance.debtRefinancing.lastProcessedWeek=-1;playerDebtRefinancing.process(game);game.g.week++;}
assert.ok(game.g.finance.debtRefinancing.history.length <= 26);
const legacy = engine.createInitialState({ configured: true });
legacy.finance = finance.defaultFinanceState(legacy);
delete legacy.finance.bankCovenants;
delete legacy.finance.creditRating;
delete legacy.finance.debtRefinancing;
delete legacy.finance.liquidityRunway;
delete legacy.finance.fundingConcentration;
delete legacy.finance.debtMaturityReserve;
const normalized = playerBankCovenants.normalize(legacy);
const normalizedRating = playerCreditRating.normalize(legacy);
const normalizedRefinancing = playerDebtRefinancing.normalize(legacy);
const normalizedLiquidity = playerLiquidityRunway.normalize(legacy);
const normalizedConcentration = playerFundingConcentration.normalize(legacy);
const normalizedReserve = playerDebtMaturityReserve.normalize(legacy);
assert.equal(normalized.status, 'compliant');
assert.deepEqual(normalized.history, []);
assert.equal(normalizedRating.grade, 'BBB');
assert.equal(normalizedRating.rateAdjustment, 0);
assert.deepEqual(normalizedRating.history, []);
assert.equal(normalizedRefinancing.status, 'scheduled');
assert.equal(normalizedRefinancing.nextMaturityWeek, legacy.week + 52);
assert.deepEqual(normalizedRefinancing.history, []);
assert.equal(normalizedLiquidity.status, 'stable');
assert.equal(normalizedLiquidity.runwayWeeks, 99);
assert.deepEqual(normalizedLiquidity.history, []);
assert.equal(normalizedConcentration.status, 'diversified');
assert.equal(normalizedConcentration.largestShare, 0);
assert.equal(normalizedConcentration.rateSurcharge, 0);
assert.deepEqual(normalizedConcentration.history, []);
assert.equal(normalizedReserve.status, 'adequate');
assert.equal(normalizedReserve.coverageRatio, 1);
assert.deepEqual(normalizedReserve.history, []);
console.log('player bank covenant, credit rating, debt refinancing, liquidity runway, funding concentration, and maturity reserve tests passed');