const assert = require('node:assert');
const { loadGame } = require('./harness');
const { modules } = loadGame({ random: () => 0.5 });
const e = new modules.engine.TycoonEngine();
const b = e.business('ramen');
const s1 = {id:'s1',businessID:'ramen',prefID:'tokyo',name:'一号',status:'open',openingWeek:1,condition:100,operatingHours:3,lastSales:0,lastProfit:0,capacity:10000};
let one = modules.market.calculateLocalMarket(e.g,b,[s1]);
const oneShare = one.results[0].marketShare;
const s2 = {...s1,id:'s2',name:'二号'};
let two = modules.market.calculateLocalMarket(e.g,b,[s1,s2]);
const r1 = two.results.find(r=>r.storeID==='s1'), r2 = two.results.find(r=>r.storeID==='s2');
assert(r1.marketShare < oneShare, 'second same-market store lowers first share');
assert(r1.marketShare + r2.marketShare <= 1, 'own share total <= 1');
assert(r1.unitsSold + r2.unitsSold <= two.marketPotential + 1e-9, 'sales units do not exceed market potential');
assert((r1.unitsSold + r2.unitsSold) < one.results[0].unitsSold * 2, 'demand is not duplicated');
const s3 = {...s1,id:'s3',prefID:'osaka',name:'大阪'};
const groups = modules.market.calculateMarketGroups(e.g,e.g.businesses,[s1,s3]);
assert(Object.keys(groups.markets).length === 2, 'different prefID creates separate local markets');
const capped = modules.market.calculateLocalMarket(e.g,b,[{...s1,capacity:20},{...s2,capacity:20000}]);
assert.strictEqual(capped.results.find(r=>r.storeID==='s1').unitsSold, 20, 'individual capacity applies');
const afterClose = modules.market.calculateLocalMarket(e.g,b,[{...s1,status:'closed'},s2]);
assert(afterClose.results.length === 1 && afterClose.results[0].storeID === 's2', 'closed store removed and demand reallocates');
const eng = new modules.engine.TycoonEngine();
eng.g.stores.push(s1,s2);
eng.advanceWeek(false);
assert.strictEqual(Object.keys(eng.g.marketLocalMarkets).length, 1, 'same local market calculated once');
assert(eng.g.marketResultsByBusinessID.ramen.marketShare === (eng.g.marketResultsByBusinessID.ramen.unitsSold / eng.g.marketResultsByBusinessID.ramen.marketPotential));
