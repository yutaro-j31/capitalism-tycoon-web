const assert = require('node:assert');
const { loadGame } = require('./harness');
const { modules } = loadGame();
const { TycoonEngine, createInitialState, migrateSave } = modules.engine;
const market = modules.market;
const v3 = createInitialState();
v3.saveVersion = 3;
v3.stores.push({id:'legacy-ramen',businessID:'ramen',prefID:'tokyo',name:'旧ラーメン',status:'open',openingWeek:1,condition:100,operatingHours:3,lastSales:12345});
const migrated = migrateSave(v3);
assert(migrated.ok, migrated.errors.join(','));
const migratedStore = migrated.state.stores[0];
assert.strictEqual(migratedStore.capacity, null, 'missing capacity remains unset');
assert(market.effectiveCapacity(migrated.state, migrated.state.businesses.find(b=>b.id==='ramen'), migratedStore) > 0);
const e = new TycoonEngine(migrated.state);
e.advanceWeek(false);
const result = e.g.marketResultsByStoreID['legacy-ramen'];
assert(result.capacity > 0 && result.unitsSold > 0 && result.sales > 0, 'migrated ramen sells');
const zero = market.calculateStoreMarket(e.g, e.business('ramen'), {...migratedStore, id:'zero', capacity:0});
assert.strictEqual(zero.unitsSold, 0, 'explicit capacity 0 stops sales');
const e2 = new TycoonEngine();
const tenant = e2.g.tenants.find(t=>t.businessID==='ramen'&&t.prefID==='tokyo');
assert(e2.openStore({tenantID:tenant.id,businessID:'ramen',name:'Reload Before Open',operatingHours:3}));
const saved = JSON.parse(JSON.stringify(e2.g));
const reloaded = new TycoonEngine(saved);
for(let i=0;i<8;i++) reloaded.advanceWeek(false);
const opened = reloaded.g.stores.find(s=>s.name==='Reload Before Open');
const newResult = reloaded.g.marketResultsByStoreID[opened.id];
assert(newResult && newResult.capacity > 0 && newResult.unitsSold > 0 && newResult.sales > 0, 'new reloaded store sells after opening');
const cafe = {id:'cafe',businessID:'cafe',prefID:'tokyo',name:'カフェ',status:'open',openingWeek:1,condition:100,operatingHours:3,lastSales:0,lastProfit:0};
reloaded.g.stores.push(cafe);
reloaded.advanceWeek(false);
assert(!reloaded.g.marketResultsByStoreID.cafe, 'non-target business not market-routed');
assert(reloaded.g.stores.find(s=>s.id==='cafe').lastSales > 0, 'non-target legacy sales still positive');
