const assert = require('node:assert');
const { loadGame } = require('./harness');
const { modules } = loadGame();
const { createInitialState, migrateSave, SAVE_VERSION, SAVE_KEY } = modules.engine;
assert.strictEqual(SAVE_KEY, 'capitalism_tycoon_web_v1');
assert.strictEqual(SAVE_VERSION, 4);
const v3 = createInitialState();
v3.saveVersion = 3;
v3.stores.push({id:'legacy-store',businessID:'ramen',prefID:'tokyo',name:'旧店',status:'open',customerSatisfaction:0,repeatRate:0});
const beforeHistory = JSON.stringify(v3.market.map(s=>s.priceHistory));
const migrated = migrateSave(v3);
assert(migrated.ok, migrated.errors.join(','));
assert.strictEqual(migrated.state.saveVersion, 4);
const store = migrated.state.stores.find(s=>s.id==='legacy-store');
assert.strictEqual(store.id, 'legacy-store');
assert.strictEqual(store.customerSatisfaction, 0, 'do not overwrite existing zero');
assert.strictEqual(store.repeatRate, 0, 'do not overwrite existing zero');
assert.deepStrictEqual(JSON.stringify(migrated.state.market.map(s=>s.priceHistory)), beforeHistory);
assert(migrateSave(migrated.state).ok, 'idempotent');
assert(!migrateSave({...v3, saveVersion:99}).ok, 'future rejected');
