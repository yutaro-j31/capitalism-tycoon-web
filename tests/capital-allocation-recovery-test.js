const assert=require('node:assert');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {loadGame}=require('./harness');
function install(load){for(const file of ['player-debt-service.js','treasury-prepayment.js','shareholder-returns.js','capital-allocation-score.js','capital-allocation-policy.js','capital-allocation-forecast.js','capital-allocation-actions.js']){const key=file.replace('.js','').replace(/-([a-z])/g,(_,c)=>c.toUpperCase());if(!load.modules[key])vm.runInContext(fs.readFileSync(path.join(__dirname,'../js',file),'utf8'),load.ctx,{filename:file});}return load;}
function publicGame(modules,cash=30_000_000,debt=100_000_000){const {engine,finance}=modules,state=engine.createInitialState({configured:true});state.week=27;state.publicCompany=true;state.selectedTab='market';state.companyCash=cash;state.companyDebt=debt;state.sharesOut=1_000_000;state.founderShares=600_000;state.stockPrice=100;state.ticker='CPTY';state.market=state.market.filter(row=>row.id!=='CPTY');state.market.push({id:'CPTY',name:state.companyName,sector:'コングロマリット',price:100,previous:100,dividendYield:0,volatility:0,trend:0,marketCap:100_000_000,per:20,pbr:2,issuedShares:1_000_000,dividendPerShare:0,shareholders:{},description:'test',listingMarket:'東証グロース',priceHistory:[{week:27,price:100}]});state.finance=finance.defaultFinanceState(state);state.finance.loans=[{id:'test-loan',loanID:'test-loan',status:'active',principal:debt,outstandingPrincipal:debt,interestRate:.12,maturityWeek:104}];return new engine.TycoonEngine(state);}
function penalty(policy,policyId,metrics,id){return policy.executionScoreBreakdown(policyId,metrics).penalties.find(row=>row.id===id).amount;}
const load=install(loadGame()),modules=load.modules,actions=modules.capitalAllocationActions,policy=modules.capitalAllocationPolicy,target=actions.recoveryTargetFor;
assert.ok(actions?.__installed);
assert.equal(modules.engine.SAVE_KEY,'capitalism_tycoon_web_v1');
assert.equal(modules.engine.SAVE_VERSION,9);
const onTrackMetrics={cash:100_000_000,debt:50_000_000,revenue:100_000_000,growthRatio:.1,payoutRatio:.2,debtReduction:0,debtReductionRatio:0},onTrackBefore=JSON.stringify(onTrackMetrics),onTrack=target('balanced',onTrackMetrics);
assert.equal(JSON.stringify(onTrackMetrics),onTrackBefore,'recovery calculation must not mutate metrics');
assert.equal(onTrack.bindingId,null);
assert.equal(onTrack.action,'maintain');
assert.equal(onTrack.requiredAmount,0);
assert.equal(onTrack.attainmentPercent,100);
assert.equal(onTrack.projectedBindingId,null);
const growthMetrics={cash:20_000_000,debt:0,revenue:100_000_000,growthRatio:0,growthSpend:0,payoutRatio:0,debtReduction:0,debtReductionRatio:0},growth=target('growth',growthMetrics);
assert.equal(growth.bindingId,'growthBelow');
assert.equal(growth.action,'growthInvestment');
assert.equal(growth.requiredAmount,8_000_000);
assert.equal(growth.executableAmount,8_000_000);
assert.equal(growth.direct,false);
assert.equal(growth.fullyFunded,true);
assert.equal(growth.attainmentPercent,0);
assert.equal(growth.projectionAvailable,false);
assert.equal(penalty(policy,'growth',{...growthMetrics,growthSpend:growth.requiredAmount,growthRatio:growth.requiredAmount/growthMetrics.revenue},'growthBelow'),0,'full growth target must remove the binding penalty');
const growthOverMetrics={cash:20_000_000,debt:0,revenue:100_000_000,growthRatio:1,growthSpend:100_000_000,payoutRatio:0,debtReduction:0,debtReductionRatio:0},growthOver=target('shareholder',growthOverMetrics);
assert.equal(growthOver.bindingId,'growthAbove');
assert.equal(growthOver.action,'growRevenue');
assert.ok(growthOver.requiredAmount>233_000_000);
assert.equal(growthOver.direct,false);
const growthOverRevenue=growthOverMetrics.revenue+growthOver.requiredAmount;
assert.equal(penalty(policy,'shareholder',{...growthOverMetrics,revenue:growthOverRevenue,growthRatio:growthOverMetrics.growthSpend/growthOverRevenue},'growthAbove'),0,'full revenue target must remove excess-growth penalty');
const leverageUnsafeMetrics={cash:30_000_000,debt:100_000_000,revenue:1_000_000,growthRatio:.1,leverageRatio:100/31,payoutRatio:0,debtReduction:0,debtReductionRatio:0},leverageUnsafe=target('balanced',leverageUnsafeMetrics);
assert.equal(leverageUnsafe.bindingId,'leverage');
assert.equal(leverageUnsafe.action,'strengthenCashBase');
assert.equal(leverageUnsafe.direct,false);
assert.ok(leverageUnsafe.requiredAmount>102_000_000);
assert.match(leverageUnsafe.text,/借入返済だけでは比率が悪化/);
assert.equal(penalty(policy,'balanced',{...leverageUnsafeMetrics,cash:leverageUnsafeMetrics.cash+leverageUnsafe.requiredAmount,leverageRatio:leverageUnsafeMetrics.debt/(leverageUnsafeMetrics.cash+leverageUnsafe.requiredAmount+leverageUnsafeMetrics.revenue)},'leverage'),0,'full balance-base target must remove leverage penalty');
const leverageMetrics={cash:100_000_000,debt:180_000_000,revenue:100_000_000,growthRatio:.1,leverageRatio:.9,payoutRatio:0,debtReduction:0,debtReductionRatio:0},leverageFundedPartially=target('balanced',leverageMetrics);
assert.equal(leverageFundedPartially.bindingId,'leverage');
assert.equal(leverageFundedPartially.action,'debtRepayment');
assert.equal(leverageFundedPartially.requiredAmount,120_000_000);
assert.equal(leverageFundedPartially.executableAmount,95_000_000);
assert.equal(leverageFundedPartially.fundingGap,25_000_000);
assert.equal(leverageFundedPartially.direct,true);
assert.equal(leverageFundedPartially.fullyFunded,false);
assert.equal(leverageFundedPartially.attainmentPercent,83.3);
assert.equal(leverageFundedPartially.projectionAvailable,true);
assert.equal(leverageFundedPartially.projectedBindingId,'leverage');
assert.equal(leverageFundedPartially.projectedRequiredAmount,25_000_000);
assert.ok(leverageFundedPartially.projectedAttainmentPercent>leverageFundedPartially.attainmentPercent);
assert.ok(leverageFundedPartially.projectedScoreGain>0);
const leverageAfterDebt=leverageMetrics.debt-leverageFundedPartially.requiredAmount,leverageAfterCash=leverageMetrics.cash-leverageFundedPartially.requiredAmount;
assert.equal(penalty(policy,'balanced',{...leverageMetrics,debt:leverageAfterDebt,cash:leverageAfterCash,leverageRatio:leverageAfterDebt/(leverageAfterCash+leverageMetrics.revenue)},'leverage'),0,'full repayment target must remove leverage penalty');
const debtMetrics={cash:100_000_000,debt:30_000_000,revenue:100_000_000,growthRatio:.1,leverageRatio:.15,payoutRatio:0,debtReduction:0,debtReductionRatio:0},debtReduction=target('deleveraging',debtMetrics);
assert.equal(debtReduction.bindingId,'debtReduction');
assert.equal(debtReduction.action,'debtRepayment');
assert.equal(debtReduction.requiredAmount,1_200_000);
assert.equal(debtReduction.executableAmount,1_200_000);
assert.equal(debtReduction.fullyFunded,true);
assert.equal(debtReduction.attainmentPercent,0);
assert.equal(debtReduction.projectedBindingId,null);
assert.equal(debtReduction.projectedScore,100);
assert.equal(debtReduction.projectedAttainmentPercent,100);
assert.equal(penalty(policy,'deleveraging',{...debtMetrics,debt:debtMetrics.debt-debtReduction.requiredAmount,debtReduction:debtReduction.requiredAmount,debtReductionRatio:debtReduction.requiredAmount/debtMetrics.debt},'debtReduction'),0,'full debt-reduction target must remove the binding penalty');
const nextBindingMetrics={cash:200_000_000,debt:270_000_000,revenue:100_000_000,growthRatio:0,growthSpend:0,leverageRatio:.9,payoutRatio:0,debtReduction:0,debtReductionRatio:0},nextBinding=target('balanced',nextBindingMetrics);
assert.equal(nextBinding.bindingId,'leverage');
assert.equal(nextBinding.requiredAmount,180_000_000);
assert.equal(nextBinding.fullyFunded,true);
assert.equal(nextBinding.projectedBindingId,'growthBelow','full repayment must reveal the next-ranked penalty');
assert.equal(nextBinding.projectedActionLabel,'成長投資の追加');
assert.equal(nextBinding.projectedRequiredAmount,2_000_000);
assert.ok(nextBinding.projectedScore>policy.executionScoreBreakdown('balanced',nextBindingMetrics).score);
const payoutMetrics={cash:100_000_000,debt:10_000_000,revenue:100_000_000,safeReturn:100_000_000,dividend:200_000_000,buyback:0,growthRatio:.1,leverageRatio:.05,payoutRatio:2,debtReduction:0,debtReductionRatio:0},payout=target('shareholder',payoutMetrics);
assert.equal(payout.bindingId,'payout');
assert.equal(payout.action,'strengthenProfitBase');
assert.equal(payout.requiredAmount,100_000_000);
assert.equal(payout.direct,false);
const payoutBase=payoutMetrics.safeReturn+payout.requiredAmount;
assert.equal(penalty(policy,'shareholder',{...payoutMetrics,safeReturn:payoutBase,payoutRatio:(payoutMetrics.dividend+payoutMetrics.buyback)/payoutBase},'payout'),0,'full profit-base target must remove payout penalty');
const repeated=target('deleveraging',debtMetrics);
assert.deepEqual(repeated,debtReduction,'recovery targets must be deterministic');
const game=publicGame(modules),warm=game.capitalAllocationPolicyRecoveryTarget('balanced'),stateBefore=JSON.stringify(game.g),engineTarget=game.capitalAllocationPolicyRecoveryTarget('balanced');
assert.deepEqual(engineTarget,warm,'engine recovery target must be deterministic');
assert.equal(JSON.stringify(game.g),stateBefore,'engine recovery target must not mutate initialized state');
game.capitalAllocationPolicyComparison=()=>({recommendedPolicy:'balanced'});
