'use strict';
const assert=require('node:assert');
const {loadGame}=require('./harness');
const g=loadGame({headless:true});
const e=new g.engineModule.TycoonEngine();
e.g.configured=true;e.g.week=120;e.g.businesses=[{id:'ramen',demand:1,unitCost:100}];e.g.activeIndustryEvent={id:'energySpike',remainingWeeks:5};e.normalize();
const logic=g.modules.industryEventResponsePlans;
assert(logic,'module is connected');
assert.equal(g.modules.finance.validate(e.g).ok,true,'fixture begins finance-valid');
const before=e.g.companyCash;
assert(before>e.getIndustryEventResponsePlanCost('supplyHedge'),'default company cash covers plan');
assert.equal(e.activateIndustryEventResponsePlan('supplyHedge'),true);
assert(e.g.companyCash<before);
assert.equal(e.g.activeIndustryEventResponsePlan.type,'supplyHedge');
assert.equal(e.activateIndustryEventResponsePlan('demandDefense'),false);
let observed=0;logic.withPlan(e,()=>{observed=e.g.businesses[0].unitCost;});
assert(observed<100);assert.equal(e.g.businesses[0].unitCost,100);
assert.equal(logic.validate(e.g).ok,true);
const financeCheck=g.modules.finance.validate(e.g);
assert.equal(financeCheck.ok,true,financeCheck.errors?.join('; ')||'finance validation failed');
e.g.activeIndustryEvent={id:'digitalBoom',remainingWeeks:4};e.normalize();
assert.equal(e.g.activeIndustryEventResponsePlan,null);
for(let x=0;x<80;x++)e.g.industryEventResponsePlanHistory.unshift({week:x,type:'fixture'});
logic.ensure(e.g);assert.equal(e.g.industryEventResponsePlanHistory.length,logic.HISTORY_LIMIT);
const restored=new g.engineModule.TycoonEngine(JSON.parse(JSON.stringify(e.g)));restored.normalize();
assert(Array.isArray(restored.g.industryEventResponsePlanHistory));
console.log('industry-event-response-plans-test: ok');
