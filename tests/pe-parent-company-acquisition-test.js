'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {loadGame}=require('./harness');

let randomCalls=0,randomState=0x6b8b4567;
const random=()=>{randomCalls+=1;randomState=(Math.imul(randomState,1664525)+1013904223)>>>0;return randomState/0x100000000;};
const {ctx,modules}=loadGame({random});
const engine=ctx.__ct_engine;
engine.configure({playerName:'PE Parent Acquisition Test',companyName:'Parent Acquisition Co',difficulty:'normal'});
engine.g.personalCash=20_000_000_000;
engine.g.companyCash=10_000_000_000;
// The fixture changes opening cash after configure(); rebuild finance opening state so
// finance.validate() audits only transactions generated by this test.
engine.g.finance=modules.finance.defaultFinanceState(engine.g);
engine.g.selectedTab='pe-portfolio';
const pf=modules.peFund,ops=modules.pePortfolioOperations;
pf.recordExit(engine.g,{exitType:'buyout',realizedAmount:200_000_000,investedAmount:8_000_000,foundedWeek:1,exitedWeek:52,profitableWeekStreak:260,employeeCount:30});
const fund=pf.createFund(engine.g,{size:10_000_000_000,gpCommit:1_000_000_000,terms:{fee:.02,carry:.2,hurdle:.08},y0:1});
const deal=ops.acquirePillarCompany(engine.g,fund.id,{businessID:'gym',enterpriseValue:2_000_000_000,useCoinvest:false,week:1});
assert(deal?.portfolioCompany,'PE holding created');
deal.companyName='PE Fitness Holdings';
deal.portfolioCompany.cash=300_000_000;
deal.portfolioCompany.weeklyRevenue=20_000_000;
deal.portfolioCompany.weeklyProfit=4_000_000;
deal.portfolioCompany.improvementScore=70;
engine.g.week=104;

const stateBeforePreview=JSON.stringify(engine.g);
const rngBeforePreview=randomCalls;
const preview=ops.previewParentCompanyAcquisition(engine.g,fund.id,deal.id);
assert.equal(preview.ok,true);
assert.equal(preview.purchasePrice,ops.previewPortfolioExit(engine.g,fund.id,deal.id,{method:'sale'}).grossProceeds,'parent purchase price equals PE production exit proceeds');
assert.equal(preview.postCompanyCash,engine.g.companyCash-preview.purchasePrice);
assert.equal(JSON.stringify(engine.g),stateBeforePreview,'parent-acquisition preview is read-only');
assert.equal(randomCalls,rngBeforePreview,'preview consumes no simulation RNG');

const savedCash=engine.g.companyCash;
engine.g.companyCash=preview.purchasePrice-1;
const unaffordable=ops.previewParentCompanyAcquisition(engine.g,fund.id,deal.id);
assert.equal(unaffordable.ok,false);
assert.equal(unaffordable.reason,'company-cash');
const fundBeforeFail=JSON.stringify(fund);
const personalBeforeFail=engine.g.personalCash;
const subBeforeFail=engine.g.subsidiaries.length;
assert.equal(engine.acquirePEPortfolioCompany(fund.id,deal.id),false,'insufficient buyer cash rejects acquisition');
assert.equal(engine.g.companyCash,preview.purchasePrice-1,'failed acquisition leaves buyer cash unchanged');
assert.equal(JSON.stringify(fund),fundBeforeFail,'failed acquisition leaves PE fund unchanged');
assert.equal(engine.g.personalCash,personalBeforeFail,'failed acquisition leaves personal cash unchanged');
assert.equal(engine.g.subsidiaries.length,subBeforeFail,'failed acquisition creates no subsidiary');

engine.g.companyCash=savedCash;
let saveCalls=0;
engine.save=()=>{saveCalls+=1;return true;};
const buyerCashBefore=engine.g.companyCash;
const personalBefore=engine.g.personalCash;
const distributedBefore=fund.distributed;
const coinvestBefore=fund.coinvestReturned;
const companyValueBefore=engine.companyValue();
const maCountBefore=engine.g.maSubsidiaries.length;
const rngBefore=randomCalls;
const plan=ops.previewParentCompanyAcquisition(engine.g,fund.id,deal.id);

assert.equal(engine.acquirePEPortfolioCompany(fund.id,deal.id),true,'company can acquire active PE holding');
assert.equal(saveCalls,1,'successful acquisition commits exactly once');
assert.equal(randomCalls,rngBefore,'parent acquisition consumes no simulation RNG');
assert.equal(buyerCashBefore-engine.g.companyCash,plan.purchasePrice,'buyer company pays the exact PE sale proceeds');
assert.equal(fund.distributed-distributedBefore,plan.settlement.distributedToFund,'PE fund receives the production waterfall fund share');
assert.equal(fund.coinvestReturned-coinvestBefore,plan.settlement.returnedToCoinvestors,'co-investors receive the production waterfall return');
assert.ok(Math.abs((engine.g.personalCash-personalBefore)-(plan.settlement.gpCarry+plan.settlement.gpPrincipalAndGain))<1,'GP economics flow to personal cash exactly once');
assert.equal(deal.status,'exited');
assert.equal(deal.exitMethod,'parent-company-acquisition');
assert.equal(deal.exitProceeds,plan.purchasePrice);
assert.equal(deal.exitAttribution.method,'parent-company-acquisition');
assert.ok(Math.abs(deal.exitAttribution.reconciliationError)<1e-6,'parent-company acquisition preserves exact exit attribution');
assert.ok(deal.exitLPFeedback?.id,'parent-company acquisition stores LP feedback for review');

const subs=engine.g.subsidiaries.filter(s=>s.sourcePEDealID===deal.id);
assert.equal(subs.length,1,'PE holding transfers into exactly one normal subsidiary');
assert.equal(engine.g.maSubsidiaries.length,maCountBefore,'conversion does not create a second M&A asset row');
const sub=subs[0];
assert.equal(sub.id,`pe-group-sub-${deal.id}-w104`,'subsidiary id is deterministic');
assert.equal(sub.sourcePEFundID,fund.id);
assert.equal(sub.ownership,1);
assert.equal(sub.acquisitionPrice,plan.purchasePrice);
assert.equal(sub.valuation,plan.purchasePrice);
assert.equal(sub.investedCost,plan.purchasePrice);
assert.equal(sub.carryingBookValue,plan.purchasePrice);
assert.equal(sub.publicCompany,false);
assert.equal(sub.portfolioCashAtAcquisition,plan.portfolioCash);
assert.equal(sub.subsidiaryCash,plan.portfolioCash);
assert.equal(deal.convertedToSubsidiaryID,sub.id);
assert.ok(Math.abs(engine.companyValue()-companyValueBefore)<1,'cash-to-subsidiary transfer does not create company value at acquisition');

const tx=engine.g.finance.transactions.filter(t=>t.sourceType==='acquirePEPortfolioCompany'&&t.sourceID===deal.id);
assert.equal(tx.length,1,'buyer books exactly one acquisition transaction');
assert.equal(tx[0].cashEffect,-plan.purchasePrice);
assert.equal(tx[0].assetEffect,plan.purchasePrice);
assert.equal(tx[0].operationID,`pe-parent-acquisition-${deal.id}`);
assert.equal(tx[0].idempotencyKey,tx[0].operationID);
assert.equal(modules.finance.validate(engine.g).ok,true,'acquisition preserves finance ledger validity');
assert.equal(engine.acquirePEPortfolioCompany(fund.id,deal.id),false,'same PE company cannot be acquired twice');
assert.equal(engine.g.subsidiaries.filter(s=>s.sourcePEDealID===deal.id).length,1);
assert.equal(engine.g.finance.transactions.filter(t=>t.sourceType==='acquirePEPortfolioCompany'&&t.sourceID===deal.id).length,1);

// Existing subsidiary / IPO-preparation system sees the converted company without another bridge.
const ipoView=modules.subsidiaryIPOPreparation.snapshot(engine.g,sub.id);
assert(ipoView,'converted company is visible to subsidiary IPO preparation');
assert.equal(ipoView.eligible,true,'converted company is IPO-preparation eligible at sufficient valuation');
assert.equal(engine.startSubsidiaryIPOPreparation(sub.id),true,'converted company can enter the existing staged IPO preparation flow');
assert.equal(sub.ipoPreparation.stageIndex,0);

// D UI: exact price/cash are shown, insufficient cash disables; sufficient cash executes through adapter.
const fund2=pf.createFund(engine.g,{size:8_000_000_000,gpCommit:0,terms:{fee:.02,carry:.2,hurdle:.08},y0:105});
const deal2=ops.acquirePillarCompany(engine.g,fund2.id,{businessID:'ramen',enterpriseValue:1_000_000_000,useCoinvest:false,week:105});
deal2.companyName='PE Ramen Holdings';
deal2.portfolioCompany.cash=100_000_000;
deal2.portfolioCompany.weeklyRevenue=10_000_000;
deal2.portfolioCompany.weeklyProfit=2_000_000;
engine.g.week=120;
const p2=ops.previewParentCompanyAcquisition(engine.g,fund2.id,deal2.id);
engine.g.companyCash=p2.purchasePrice-1;

const listeners=new Map();
const screen={innerHTML:'',classList:{add(){},remove(){}}};
const document={
  addEventListener(type,cb){listeners.set(type,cb);},
  querySelector(){return null;},
  getElementById(id){return id==='screen'?screen:null;}
};
const uiContext=vm.createContext({console,document,CapitalismTycoonPEUIAdapter:modules.peUIAdapter});
new vm.Script(fs.readFileSync('js/pe-ui.js','utf8'),{filename:'js/pe-ui.js'}).runInContext(uiContext);
function targetFor(selector,dataset={}){return {dataset,closest(q){return q===selector?this:null;},matches(){return false;}};}
function click(selector,dataset={}){listeners.get('click')({target:targetFor(selector,dataset),preventDefault(){}});}
click('[data-pe-view]',{peView:'portfolio'});
click('[data-pe-portfolio-open]',{pePortfolioOpen:deal2.id});
assert.match(screen.innerHTML,/自社でM&A・子会社化/);
assert.match(screen.innerHTML,/自社cash不足/);
assert.match(screen.innerHTML,/data-pe-parent-acquire[^>]*disabled/,'insufficient company cash disables acquisition action');

engine.g.companyCash=p2.purchasePrice+100_000_000;
uiContext.CapitalismTycoonPEUI.render();
assert.doesNotMatch(screen.innerHTML,/data-pe-parent-acquire[^>]*disabled/,'funded buyer can execute acquisition');
click('[data-pe-parent-acquire]',{peFund:fund2.id,peDeal:deal2.id});
assert.equal(deal2.status,'exited','D UI parent acquisition reaches production transfer');
assert.equal(engine.g.subsidiaries.filter(s=>s.sourcePEDealID===deal2.id).length,1);
assert.match(screen.innerHTML,/data-pe-view-root="portfolio-exit-result"/,'after transfer D UI opens the exit answer screen');
assert.match(screen.innerHTML,/Exitの答え合わせ/);
assert.match(screen.innerHTML,/LP FEEDBACK/);
assert.match(screen.innerHTML,/取得価格差/);
assert.match(screen.innerHTML,/オペレーション/);
assert.match(screen.innerHTML,/市況/);

const source=fs.readFileSync('js/pe-portfolio-operations.js','utf8');
const added=source.slice(source.indexOf('function previewParentCompanyAcquisition'),source.indexOf('// Exit（現在production',source.indexOf('function previewParentCompanyAcquisition')));
assert.doesNotMatch(added,/Math\.random|Date\.now|randomUUID|\buuid\s*\(/,'PE parent-acquisition path uses deterministic IDs only');

console.log('PE parent-company acquisition, normal subsidiary conversion, accounting and IPO preparation tests passed');
