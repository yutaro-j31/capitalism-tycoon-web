const assert=require('node:assert');
const {loadGame}=require('./harness');
const target=process.env.RIVALRY_TEST_STAGE||'all';
const checkpoint=name=>{if(target===name){console.log(`competitor rivalry ${name} checkpoint ok`);process.exit(0);}};
const ctx=loadGame({random:()=>0.5});
const {engine,competitor}=ctx.modules;
const competitorRivalry=competitor.rivalry;
assert.ok(competitorRivalry,'competitor rivalry extension should load');
checkpoint('module');
const g=engine.createInitialState({configured:true});
competitor.ensure(g);
assert.equal(g.saveVersion,engine.SAVE_VERSION);
const c=g.competitorStates.find(x=>x.active&&x.marketPresence&&x.marketPresence.some(p=>p.active));
assert.ok(c,'active competitor should exist');
const p=c.marketPresence.find(x=>x.active);
assert.ok(p,'active competitor presence should exist');
assert.equal(c.rivalry.mode,'neutral');
const business=g.businesses.find(b=>b.id==='ramen');
business.price=p.price;
g.stores.push({id:'rivalry-player-store-1',businessID:'ramen',prefID:p.prefID,name:'プレイヤー1号店',status:'open',quality:60,brand:45,condition:100,operatingHours:3,openingWeek:1,weeksToOpen:0});
g.marketResultsByStoreID={'rivalry-player-store-1':{marketShare:.10}};
g.week=2;
competitor.processWeek(g);
assert.ok(c.rivalry.lastObservedSignals,'first week should establish a public-signal baseline');
assert.equal(c.rivalry.mode,'neutral');
checkpoint('baseline');
const priorPrice=p.price;
business.price=Math.round(priorPrice*.88);
g.marketResultsByStoreID['rivalry-player-store-1']={marketShare:.18};
p.currentWeekShare=.12;
g.week=3;
competitor.processWeek(g);
assert.equal(c.rivalry.mode,'price_war');
assert.equal(c.rivalry.modeName,'価格戦争');
assert.ok(c.rivalry.untilWeek>g.week);
checkpoint('trigger');
const action=g.competitorActions.find(a=>a.competitorID===c.competitorID&&a.decisionWeek===3&&a.actionType==='priceDecrease');
assert.ok(action,'price-war response should queue a price decrease');
checkpoint('action-queued');
assert.ok(action.newValue<priorPrice);
assert.ok(action.reasonCodes.includes('rivalry'));
checkpoint('action-details');
assert.ok(g.competitorEvents.some(x=>String(x&&x.text||x).includes('価格戦争')));
checkpoint('event');
assert.equal(g.competitorProjects.some(project=>project.actionID===action.actionID),false,'pricing responses remain lightweight actions rather than capital projects');
checkpoint('project');
const actionCount=g.competitorActions.length;
competitor.processWeek(g);
assert.equal(g.competitorActions.length,actionCount,'same-week rerun must not duplicate rivalry actions');
checkpoint('idempotency');
g.week=4;
competitor.processWeek(g);
assert.equal(p.price,action.newValue,'queued rivalry price response should apply on its effective week');
checkpoint('apply');
const version=g.saveVersion;
delete c.rivalry;
competitor.ensure(g);
assert.equal(g.saveVersion,version,'rivalry migration must not change save version');
assert.equal(c.rivalry.mode,'neutral');
checkpoint('migration');
assert.doesNotThrow(()=>competitor.validate(g));
checkpoint('validation');
console.log('competitor rivalry AI ok');
