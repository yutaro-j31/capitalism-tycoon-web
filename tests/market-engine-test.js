const assert = require('node:assert');
const { loadGame, findStateIssues } = require('./harness');
const { modules } = loadGame({ random: () => 0.42 });
const { TycoonEngine } = modules.engine;
const market = modules.market;
assert(market.validateSegments(), 'segment weights must total 1');
const e = new TycoonEngine();
e.g.stores.push({id:'s1',businessID:'ramen',prefID:'tokyo',name:'標準店',status:'open',openingWeek:1,openedWeek:1,condition:100,operatingHours:3,lastSales:0,lastProfit:0,quality:18,brand:10,customerSatisfaction:55,repeatRate:.22});
const b = e.business('ramen'), s = e.g.stores[0];
const base = market.calculateStoreMarket(e.g,b,s);
assert(market.validateResult(base));
assert(base.unitsSold <= base.capacity + 1e-9);
assert(base.marketShare >= 0 && base.marketShare <= 1);
const highPriceB = {...b, price:b.price*1.35};
const high = market.calculateStoreMarket(e.g, highPriceB, s);
assert(high.potentialDemand < base.potentialDemand, 'price increase lowers demand');
const lowPriceB = {...b, price:Math.max(1,b.unitCost*.7)};
const low = market.calculateStoreMarket(e.g, lowPriceB, s);
assert(low.unitsSold >= base.unitsSold || low.potentialDemand >= base.potentialDemand, 'discount raises quantity/demand');
assert(low.marginalProfitRate < base.marginalProfitRate, 'below-cost/discount can worsen margin');
const quality = market.calculateStoreMarket(e.g, {...b, quality:b.quality+50}, s);
const qBase = base.segments.find(x=>x.id==='quality').playerShare;
const qNew = quality.segments.find(x=>x.id==='quality').playerShare;
assert(qNew > qBase, 'quality segment share improves');
const brand = market.calculateStoreMarket(e.g, {...b, brand:b.brand+60}, s);
assert(brand.segments.find(x=>x.id==='trend').playerShare > base.segments.find(x=>x.id==='trend').playerShare, 'brand segment share improves');
const convenient = market.calculateStoreMarket(e.g, b, {...s, operatingHours:4});
assert(convenient.segments.find(x=>x.id==='convenience').playerShare >= base.segments.find(x=>x.id==='convenience').playerShare, 'convenience share improves');
const capped = market.calculateStoreMarket(e.g, b, {...s, capacity:10});
assert(capped.unitsSold === 10 && capped.lostDemand > 0, 'capacity caps sales and records lost demand');
const again = market.calculateStoreMarket(e.g,b,s);
assert.deepStrictEqual(JSON.stringify(again), JSON.stringify(base), 'deterministic');
const issues = findStateIssues(base, 'marketResult');
assert.deepStrictEqual(issues, []);
