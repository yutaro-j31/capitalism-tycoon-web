const assert = require('node:assert/strict');
const fs = require('node:fs');
const { readIndex, loadGame } = require('./harness');
const app = fs.readFileSync('js/app.js', 'utf8');
const css = fs.readFileSync('css/app.css', 'utf8');
const html = readIndex();
assert.match(html, /js\/founding-tutorial\.js.*js\/app\.js/, 'founding tutorial loads before app');
assert.match(app, /data-founding-guide="1"/, 'founding guide card renders on CEO Dashboard');
assert.match(app, /data-ceo-dashboard-card="\$\{esc\(id\)\}"/, 'fold cards expose dashboard selectors');
assert.match(app, /fold\('weekly-impact','直近週間インパクト'/, 'weekly impact card is rendered');
assert.match(app, /dashboardModule\.weeklyImpact/, 'weekly impact card reuses existing model');
assert.match(app, /data-focus="\$\{esc\(current\.targetSelector\)\}"/, 'guide CTA uses model selector');
assert.match(app, /進行済みセーブの創業ガイド/, 'summary mode heading is implemented');
assert.match(app, /model\.displayMode==='summary'/, 'summary mode is consumed by UI');
assert.match(app, /創業チュートリアル完了/, 'complete mode heading is implemented');
assert.match(app, /aria-live="polite"/, 'aria-live is present');
assert.match(app, /aria-current="\$\{s\.current\?'step':'false'\}"/, 'current step is exposed');
assert.match(app, /aria-label="創業ロードマップ詳細"/, 'details has accessible label');
assert.match(app, /data-action="founding-tutorial-jump"/, 'read-only navigation button renders');
assert.match(app, /case 'founding-tutorial-jump':engine\.g\.selectedTab=el\.dataset\.tab\|\|'home';render\(\);requestAnimationFrame/, 'jump only changes tab and focuses');
assert.doesNotMatch(app.match(/case 'founding-tutorial-jump':[\s\S]*?break;/)[0], /engine\.save|advanceWeek|openStore|borrow|repay|hire|invest/, 'guide jump does not execute game actions or save');
assert.match(app, /Executive Secretary/, 'role split note is rendered');
assert.match(css, /\.btn\.small\.founding-guide-cta\s*\{[^}]*min-height:44px/, 'founding guide CTA keeps a 44px tap target with enough specificity to override .btn.small');
assert.match(css, /@media\(max-width:430px\)/, 'narrow iPhone width rule exists');
assert.match(css, /@media\(prefers-reduced-motion:reduce\)/, 'reduced motion rule exists');
assert.match(css, /focus-visible/, 'keyboard focus style exists');
const firstLoad = loadGame();
const save = firstLoad.modules.engine.createInitialState({ configured: true });
save.week = 2;
save.reports = [{ week: 1, sales: 1000, profit: 100, expenses: 900 }];
save.lastReport = save.reports[0];
const loaded = loadGame({ localStorageInitial: { capitalism_tycoon_web_v1: JSON.stringify(save) } });
const rendered = loaded.ctx.document.getElementById('app').innerHTML;
assert.match(rendered, /data-ceo-dashboard-card="weekly-impact"/, 'weekly impact selector exists in rendered dashboard');
assert.match(rendered, /前週比較なし/, 'first weekly impact state explains missing comparison');
assert.match(rendered, /週間インパクトを読む/, 'one report makes weekly recap the current visible guide step');
const before = loaded.ctx.__localStorageHistory.setItem.length;
loaded.modules.foundingTutorial.build(loaded.ctx.__ct_engine.g);
assert.equal(loaded.ctx.__localStorageHistory.setItem.length, before, 'rendered guide model check does not save');
console.log('founding tutorial UI tests passed');
