const { loadGame } = require('./harness');
const { engineModule, modules } = loadGame();
function assert(cond,msg){if(!cond)throw new Error(msg);}
const e=new engineModule.TycoonEngine();
e.g.configured=true;
e.g.companyCash=1_000_000_000;
e.g.personalCash=500_000_000;
e.g.companyDebt=0;e.g.personalDebt=0;
e.g.finance=modules.finance.defaultFinanceState(e.g);
const property=e.g.properties.find(p=>!p.owner);
assert(property,'property missing');
property.owner='company';
property.purchasePrice=property.price||property.value||100_000_000;
property.buildingType='賃貸マンション';
assert(e.enablePropertyRental(property.id,{monthlyRent:2_000_000,targetOccupancy:.92})===true,'enable rental failed');
const cashBefore=e.g.companyCash;
e.advanceWeek(false);
const metrics=e.getPropertyInvestmentMetrics(property.id);
assert(metrics,'metrics missing');
assert(metrics.occupancy>0&&metrics.occupancy<=1,'occupancy invalid');
assert(metrics.grossYield>0,'gross yield invalid');
assert(metrics.collateralValue>0,'collateral invalid');
assert(metrics.landValue>0&&metrics.buildingValue>0,'land/building split missing');
assert(Math.abs(metrics.valuation-(metrics.landValue+metrics.buildingValue))<2,'split valuation mismatch');
assert(e.g.realEstate.ledger.length===1,'weekly ledger missing');
assert(e.g.companyCash!==cashBefore,'company cash not updated');
assert(e.g.finance.transactions.some(t=>t.sourceType==='property-rent'&&t.sourceID===property.id),'rent finance event missing');
const count=e.g.realEstate.ledger.length;
modules.realEstate.processWeek(e);
assert(e.g.realEstate.ledger.length===count,'same week processed twice');
const borrowAmount=Math.floor(metrics.collateralAvailable*.4),companyBeforeBorrow=e.g.companyCash;
const companyLoan=e.borrowAgainstProperty(property.id,borrowAmount,{termWeeks:52,interestRate:.05});
assert(companyLoan,'company collateral loan failed');
assert(e.g.companyCash===companyBeforeBorrow+borrowAmount,'company borrowing cash mismatch');
assert(e.g.companyDebt===borrowAmount,'company debt mismatch');
assert(e.g.finance.transactions.some(t=>t.sourceType==='property-collateral-borrowing'&&t.sourceID===companyLoan),'company borrowing finance event missing');
assert(e.sellPropertyInvestment(property.id)===false,'collateralized property sale should be blocked');
const repayment=e.repayPropertyLoan(companyLoan,Math.floor(borrowAmount/4));
assert(repayment>0,'company prepayment failed');
assert(e.g.companyDebt===borrowAmount-repayment,'company debt repayment mismatch');
const personal=e.g.properties.find(p=>!p.owner&&p.id!==property.id);
assert(personal,'personal property missing');
personal.owner='personal';personal.purchasePrice=personal.price||personal.value||50_000_000;personal.buildingType='賃貸アパート';
assert(e.enablePropertyRental(personal.id,{monthlyRent:800_000})===true,'personal rental failed');
const personalMetrics=e.getPropertyInvestmentMetrics(personal.id),personalBorrow=Math.floor(personalMetrics.collateralAvailable*.25),personalCashBeforeBorrow=e.g.personalCash,companyCashBeforePersonalBorrow=e.g.companyCash;
const personalLoan=e.borrowAgainstProperty(personal.id,personalBorrow,{termWeeks:104});
assert(personalLoan,'personal collateral loan failed');
assert(e.g.personalCash===personalCashBeforeBorrow+personalBorrow,'personal borrowing cash mismatch');
assert(e.g.personalDebt===personalBorrow,'personal debt mismatch');
assert(e.g.companyCash===companyCashBeforePersonalBorrow,'personal borrowing leaked into company cash');
const personalBefore=e.g.personalCash,companyBefore=e.g.companyCash;
e.advanceWeek(false);
assert(e.g.personalCash!==personalBefore,'personal cash not updated');
const personalRow=e.g.realEstate.ledger.find(r=>r.propertyID===personal.id);
assert(personalRow,'personal ledger missing');
assert(Math.abs(e.g.companyCash-companyBefore)<Math.abs(personalRow.netIncome)+20_000_000,'personal income leaked into company cash');
const saleProperty=e.g.properties.find(p=>!p.owner&&p.id!==property.id&&p.id!==personal.id);
assert(saleProperty,'sale property missing');
saleProperty.owner='company';saleProperty.purchasePrice=saleProperty.price||saleProperty.value||80_000_000;saleProperty.buildingType='賃貸ビル';modules.realEstate.ensure(e.g);
const sale=e.sellPropertyInvestment(saleProperty.id);
assert(sale&&sale.propertyID===saleProperty.id,'investment property sale failed');
assert(Math.abs(sale.totalProceeds-(sale.landProceeds+sale.buildingProceeds))<2,'sale proceeds split mismatch');
assert(Math.abs(sale.totalGain-(sale.landGain+sale.buildingGain))<2,'sale gain split mismatch');
assert(e.g.realEstate.sales.some(x=>x.saleID===sale.saleID),'sale history missing');
const raw=JSON.parse(JSON.stringify(e.g));delete raw.realEstate;for(const p of raw.properties)delete p.realEstate;
const migrated=new engineModule.TycoonEngine(raw);modules.realEstate.ensure(migrated.g);
assert(migrated.g.realEstate.schemaVersion===2,'migration failed');
assert(migrated.g.properties.every(p=>p.realEstate),'property migration failed');
assert(migrated.g.properties.every(p=>Number.isFinite(p.realEstate.landValue)&&Number.isFinite(p.realEstate.buildingValue)),'split valuation migration failed');
console.log('real estate foundation checks passed');