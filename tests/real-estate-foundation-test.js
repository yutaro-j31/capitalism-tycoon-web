const { loadGame } = require('./harness');
const { engineModule, modules } = loadGame();
function assert(cond,msg){if(!cond)throw new Error(msg);}
const e=new engineModule.TycoonEngine();
e.g.configured=true;
e.g.companyCash=1_000_000_000;
e.g.personalCash=500_000_000;
e.g.finance=modules.finance.defaultFinanceState(e.g);
const property=e.g.properties.find(p=>!p.owner);
assert(property,'property missing');
property.owner='company';
property.purchasePrice=property.price||property.value||100_000_000;
property.buildingType='賃貸マンション';
assert(e.enablePropertyRental(property.id,{monthlyRent:2_000_000,targetOccupancy:.92})===true,'enable rental failed');
const cashBefore=e.g.companyCash;
e.advanceWeek(false);
const metrics=e.getPropertyInvestmentMetrics(property.id);
assert(metrics,'metrics missing');
assert(metrics.occupancy>0&&metrics.occupancy<=1,'occupancy invalid');
assert(metrics.grossYield>0,'gross yield invalid');
assert(metrics.collateralValue>0,'collateral invalid');
assert(e.g.realEstate.ledger.length===1,'weekly ledger missing');
assert(e.g.companyCash!==cashBefore,'company cash not updated');
assert(e.g.finance.transactions.some(t=>t.sourceType==='property-rent'&&t.sourceID===property.id),'rent finance event missing');
const count=e.g.realEstate.ledger.length;
modules.realEstate.processWeek(e);
assert(e.g.realEstate.ledger.length===count,'same week processed twice');
const personal=e.g.properties.find(p=>!p.owner&&p.id!==property.id);
assert(personal,'personal property missing');
personal.owner='personal';personal.purchasePrice=personal.price||personal.value||50_000_000;personal.buildingType='賃貸アパート';
assert(e.enablePropertyRental(personal.id,{monthlyRent:800_000})===true,'personal rental failed');
const personalBefore=e.g.personalCash,companyBefore=e.g.companyCash;
e.advanceWeek(false);
assert(e.g.personalCash!==personalBefore,'personal cash not updated');
const personalRow=e.g.realEstate.ledger.find(r=>r.propertyID===personal.id);
assert(personalRow,'personal ledger missing');
assert(Math.abs(e.g.companyCash-companyBefore)<Math.abs(personalRow.netIncome)+10_000_000,'personal income leaked into company cash');
const raw=JSON.parse(JSON.stringify(e.g));delete raw.realEstate;for(const p of raw.properties)delete p.realEstate;
const migrated=new engineModule.TycoonEngine(raw);modules.realEstate.ensure(migrated.g);
assert(migrated.g.realEstate.schemaVersion===1,'migration failed');
assert(migrated.g.properties.every(p=>p.realEstate),'property migration failed');
console.log('real estate foundation checks passed');
