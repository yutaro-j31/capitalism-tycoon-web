const { loadGame } = require('./harness');
const { engineModule, modules } = loadGame();
const e=new engineModule.TycoonEngine(); e.g.configured=true; const f=modules.finance;
const opening=e.g.companyCash;
f.event(e.g,'revenue',1000,{cashEffect:1000,profitEffect:1000,sourceType:'b2c-store',operationID:'b2c'}); e.g.companyCash+=1000;
f.event(e.g,'revenue',1000,{cashEffect:700,profitEffect:1000,sourceType:'b2b-invoice',operationID:'b2b'}); e.g.companyCash+=700;
f.event(e.g,'accountsReceivableCollection',300,{cashEffect:300,profitEffect:0,sourceType:'ar-collection',operationID:'ar'}); e.g.companyCash+=300;
f.event(e.g,'taxExpense',100,{cashEffect:0,profitEffect:-100,sourceType:'tax',operationID:'tax-exp'});
f.event(e.g,'taxPayment',40,{cashEffect:-40,profitEffect:0,sourceType:'tax',operationID:'tax-pay'}); e.g.companyCash-=40;
f.recordSnapshot(e.g,opening,e.g.week,e.g.companyCash);
f.recordWeekly(e.g,{beginningCash:opening,stores:[],other:{}});
const st=f.buildStatements(e.g,'52'), wc=st.workingCapital, cf=st.cashFlow;
if(wc.accountsReceivable!==0) throw new Error(`AR expected 0 after collection, got ${wc.accountsReceivable}`);
if(wc.accruedTaxes!==60) throw new Error(`tax accrual expected 60, got ${wc.accruedTaxes}`);
if(cf.accountsReceivableChange!==0) throw new Error(`AR change expected 0, got ${cf.accountsReceivableChange}`);
if(cf.accruedTaxesChange!==60) throw new Error(`tax change expected 60, got ${cf.accruedTaxesChange}`);
if(e.g.companyCash!==opening+1960) throw new Error('companyCash working capital mismatch');
if(Math.abs(cf.openingCash+cf.netCashChange-cf.endingCash)>0.1) throw new Error('CF identity failed');
console.log('working capital checks passed');
