const assert = require('node:assert/strict');
const { loadGame } = require('./harness');
const { modules } = loadGame();
const e = new modules.engine.TycoonEngine();
e.g.configured = true; e.g.hasHeadOffice = true; e.g.officeCapacity = 50; e.g.companyCash = 100000000;
e.g.departments.hr = { ...modules.data.MASTER.departments.find(d => d.id === 'hr'), established: true }; e.g.departmentStaff.hr = 2;
modules.workforce.migrateV7(e.g);
const before = JSON.stringify(e.g);
assert.equal(modules.workforce.validate(e.g).ok, true);
assert.equal(JSON.stringify(e.g), before);
const broken = JSON.parse(JSON.stringify(e.g));
delete broken.workforceTeams; delete broken.nextCandidateSeq;
const brokenBefore = JSON.stringify(broken);
const result = modules.workforce.validate(broken);
assert.equal(JSON.stringify(broken), brokenBefore);
assert.equal(result.ok, false);
assert(result.errors.some(e => e.includes('workforceTeams')));
assert.equal(Object.prototype.hasOwnProperty.call(broken, 'workforceTeams'), false);
console.log('workforce validate purity ok');
