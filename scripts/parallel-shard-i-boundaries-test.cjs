'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const { inventory, manifest } = require('./parallel-shard-i-boundaries.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'i-boundaries-'));
try {
  fs.mkdirSync(path.join(root, 'tests'));
  const write = (p, s) => fs.writeFileSync(path.join(root, p), s);
  write('package.json', JSON.stringify({ scripts: { probe: 'node tests/a.js', opaque: 'node tests/a.js && echo unsafe' } }));
  write('tests/a.js', "throw Error('MUST NOT EXECUTE');require('./b');require('./missing');\nfs.writeFileSync('shared', 'x');server.listen(0);\n");
  write('tests/b.js', "require('./c');require('./a');cp.spawnSync('node',[]);\n");
  write('tests/c.js', "require('./d');new vm.Script('code').runInContext({});\n");
  write('tests/d.js', "fs.rmSync('hidden');\n");
  const command = { index:0, label:'probe', command:'npm', args:['run','probe','--silent'] };
  const before = fs.readFileSync(path.join(root,'tests/a.js'));
  const report = inventory(root, [command]), row = report.invocations[0];
  assert.equal(row.entry, 'tests/a.js'); assert.equal(row.npmScript, 'node tests/a.js');
  assert.deepEqual(row.files.map(f=>f.path), ['tests/a.js','tests/b.js','tests/c.js']);
  assert.ok(row.files[0].hits.some(h=>h.kind==='filesystem' && h.line===2));
  assert.ok(row.files[0].hits.some(h=>h.kind==='port'));
  assert.ok(row.files[1].hits.some(h=>h.kind==='child-process'));
  assert.ok(row.files[2].hits.some(h=>h.kind==='dynamic-code'));
  assert.ok(row.gaps.some(g=>g.kind==='depth-boundary' && g.target==='tests/d.js'));
  assert.ok(row.gaps.some(g=>g.kind==='unresolved-relative-require'));
  assert.equal(report.dependencyClosureVerified, false); assert.equal(report.runtimeExecuted, false);
  assert.equal(report.sharedWriteSafetyQualified, false); assert.equal(report.parallelExecutionQualified, false);
  assert.equal(report.productionAuthorized, false);
  assert.deepEqual(fs.readFileSync(path.join(root,'tests/a.js')),before);
  const deeper = inventory(root,[command],3);
  assert.ok(deeper.invocations[0].files.some(f=>f.path==='tests/d.js'));
  write('tests/b.js', "cp.spawnSync('other',[]);\n");
  assert.notEqual(inventory(root,[command]).invocations[0].files[1].sha256,row.files[1].sha256);
  const opaque = inventory(root,[{...command,args:['run','opaque','--silent']}]).invocations[0];
  assert.deepEqual(opaque.files,[]); assert.equal(opaque.gaps[0].kind,'unresolved-npm-script');
  assert.equal(inventory(root,[{...command,command:'sh',args:['-c','anything']}]).invocations[0].gaps[0].kind,'unresolved-command');
  assert.throws(()=>manifest(root,'short'),/full source SHA/);
  fs.symlinkSync(__filename,path.join(root,'tests/escape.js'));
  assert.throws(()=>inventory(root,[{...command,command:'node',args:['tests/escape.js']}]),/inside root/);
  console.log('I source boundaries: PASS (lexical metadata only; no workload or parallel safety qualification)');
} finally { fs.rmSync(root,{recursive:true,force:true}); }

require('./parallel-shard-index-inputs-test.cjs');
